//
//  UITestGenerator.swift
//  AgenticDesigner
//
//  Layer five of the product-truth check. Today the proof stops at "the app
//  launched in a simulator" — a human still has to believe the flows work.
//  But the flows exist as DATA, so the navigation they promise can be turned
//  into an XCUITest that actually taps through it. That turns "it works" from
//  something the agent asserts into something a machine demonstrates.
//
//  Only reachable, deterministic assertions are emitted: an element the
//  designer named, a tap on a control that has a navigate flow, and the
//  appearance of the destination screen. Anything requiring credentials or a
//  network round-trip is deliberately left out — a test that needs a live
//  backend fails for reasons that have nothing to do with the design.
//

import Foundation

enum UITestGenerator {

    struct NavigationCase {
        let buttonIdentifier: String
        let buttonName: String
        let destinationIdentifier: String
        let destinationScreen: String
    }

    /// Builds the XCUITest source for a project's screens and flows.
    static func source(
        appName: String,
        screens: [DesignNode],
        flows: [LogicFlow]
    ) -> String {
        let firstScreen = screens.first
        let launchAssertions = (firstScreen?.children ?? [])
            .filter { isAssertable($0) }
            .prefix(4)
            .map { node in
                """
                        XCTAssertTrue(
                            app.descendants(matching: .any)["\(LogicExporter.accessibilityIdentifier(for: node))"].waitForExistence(timeout: 5),
                            "\(node.name) should be visible on \(firstScreen?.name ?? "the first screen")"
                        )
                """
            }
            .joined(separator: "\n")

        let navigationCases = navigationCases(screens: screens, flows: flows)
        let navigationTests = navigationCases.enumerated().map { index, testCase in
            """
                /// \(testCase.buttonName) promises navigation to \(testCase.destinationScreen) — this proves it.
                func testNavigation\(index + 1)_\(sanitize(testCase.buttonName))To\(sanitize(testCase.destinationScreen))() throws {
                    let app = XCUIApplication()
                    app.launch()

                    let control = app.descendants(matching: .any)["\(testCase.buttonIdentifier)"]
                    XCTAssertTrue(control.waitForExistence(timeout: 5), "\(testCase.buttonName) should exist")
                    control.tap()

                    XCTAssertTrue(
                        app.descendants(matching: .any)["\(testCase.destinationIdentifier)"].waitForExistence(timeout: 5),
                        "Tapping \(testCase.buttonName) should show \(testCase.destinationScreen)"
                    )
                }
            """
        }.joined(separator: "\n\n")

        let noNavigationNote = navigationCases.isEmpty
            ? """

                // No navigation test was generated: no control on these screens has a
                // navigate flow bound to it yet. Wire one with apply_logic_actions and
                // re-export to get a real end-to-end assertion here.
            """
            : ""

        return """
        //
        //  \(appName)UITests.swift
        //  Generated by AgenticDesigner — do not hand-edit; regenerate instead.
        //
        //  These tests address elements by the accessibility identifiers the
        //  exporter derives from your layer names, so renaming a layer renames
        //  its test hook too.
        //

        import XCTest

        final class \(appName)UITests: XCTestCase {

            override func setUpWithError() throws {
                continueAfterFailure = false
            }

            /// The app launches and the first screen renders its content.
            func testLaunchesAndShowsFirstScreen() throws {
                let app = XCUIApplication()
                app.launch()
                XCTAssertTrue(app.wait(for: .runningForeground, timeout: 10), "App should reach the foreground")
        \(launchAssertions.isEmpty ? "        // The first screen has no named elements to assert." : launchAssertions)
            }
        \(noNavigationNote)
        \(navigationTests)
        }

        """
    }

    /// A control is testable when a tap on it runs a flow containing a
    /// navigate block, and the destination screen has something to assert.
    static func navigationCases(screens: [DesignNode], flows: [LogicFlow]) -> [NavigationCase] {
        var cases: [NavigationCase] = []
        let allNodes = screens.flatMap { flatten($0) }

        for flow in flows {
            // The tap target this flow hangs off.
            guard let event = flow.blocks.first(where: { $0.type == .onTap }) else { continue }
            let boundId = event.connectedDesignNodeId
                ?? event.parameters.compactMap(\.nodeReference).first
            guard let boundId, let control = allNodes.first(where: { $0.id == boundId }) else { continue }

            // Where it says it goes.
            guard let navigate = flow.blocks.first(where: { $0.type == .navigate }),
                  let destinationId = navigate.parameters.first(where: { $0.key == "screen" })?.nodeReference,
                  let destination = screens.first(where: { $0.id == destinationId }),
                  let anchor = destination.children.first(where: { isAssertable($0) })
            else { continue }

            cases.append(NavigationCase(
                buttonIdentifier: LogicExporter.accessibilityIdentifier(for: control),
                buttonName: control.name,
                destinationIdentifier: LogicExporter.accessibilityIdentifier(for: anchor),
                destinationScreen: destination.name
            ))
        }
        return cases
    }

    /// Text and controls make stable anchors; decorative art does not.
    private static func isAssertable(_ node: DesignNode) -> Bool {
        switch node.type {
        case .Text, .Button, .Input: return !node.name.isEmpty
        default: return false
        }
    }

    private static func flatten(_ node: DesignNode) -> [DesignNode] {
        [node] + node.children.flatMap { flatten($0) }
    }

    private static func sanitize(_ raw: String) -> String {
        let cleaned = raw
            .replacingOccurrences(of: "[^A-Za-z0-9]+", with: "", options: .regularExpression)
        return cleaned.isEmpty ? "Element" : cleaned
    }
}
