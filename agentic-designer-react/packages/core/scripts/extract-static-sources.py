"""Extracts the fully-static Swift multiline literals out of
AgenticDesigner/Services/LogicExporter.swift into TypeScript, so the ported
exporter emits byte-identical Swift. Re-run after changing the Swift source:
    python3 scripts/extract-static-sources.py
"""
import re, sys, os

SWIFT = '/Users/ariel/Documents/XcodeApps/AgenticDesigner/AgenticDesigner/Services/LogicExporter.swift'
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'services', 'logicExporter', 'staticSources.ts')

src = open(SWIFT, encoding='utf-8').read()
lines = src.split('\n')

def literal_after(func_name):
    """Returns (raw_lines, indent) of the first multiline literal in func."""
    start = None
    for i, l in enumerate(lines):
        if re.search(r'func %s\(' % re.escape(func_name), l):
            start = i
            break
    if start is None:
        raise SystemExit('function not found: ' + func_name)
    for i in range(start, len(lines)):
        if lines[i].rstrip().endswith('"""'):
            open_i = i
            break
    for j in range(open_i + 1, len(lines)):
        if lines[j].lstrip().startswith('"""'):
            close_i = j
            break
    indent = len(lines[close_i]) - len(lines[close_i].lstrip())
    body = []
    for l in lines[open_i + 1:close_i]:
        body.append(l[indent:] if len(l) >= indent else l.strip())
    return body

def unescape_swift(text):
    """Swift multiline literal escapes → the characters they produce.
    Raises on a real interpolation (these blocks must be static)."""
    out = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == '\\' and i + 1 < len(text):
            nxt = text[i + 1]
            if nxt == '\\': out.append('\\'); i += 2; continue
            if nxt == '"': out.append('"'); i += 2; continue
            if nxt == 'n': out.append('\n'); i += 2; continue
            if nxt == 't': out.append('\t'); i += 2; continue
            if nxt == '0': out.append('\0'); i += 2; continue
            if nxt == '(':
                raise ValueError('interpolation in a supposedly static literal: ' + text[i:i+40])
        out.append(ch)
        i += 1
    return ''.join(out)

def ts_literal(text):
    return text.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')

FUNCS = [
    ('sensorServicesSource', 'Real hardware for the exported app: CoreLocation / HealthKit / CoreMotion services.'),
    ('watchWorkoutSource', 'A real HKWorkoutSession with a live heart-rate stream + WatchConnectivity sync.'),
    ('authServiceSource', 'Session restoration, email verification and guest mode.'),
    ('permissionsSource', 'Progressive permissions — asked in context, not all at launch.'),
    ('storeServiceSource', 'Real StoreKit 2 purchases (never a fake success).'),
    ('pushServiceSource', 'Real APNs registration (iOS).'),
    ('persistenceSource', 'Keychain for secrets + crash-safe StateStore.'),
    ('privacyManifestSource', "Apple's required privacy manifest for the UserDefaults/file APIs used."),
    ('firebaseDeployConfigJSON', 'firebase.json, so `firebase deploy --only firestore:rules` actually runs.'),
]

parts = ["""// GENERATED by scripts/extract-static-sources.py from
// AgenticDesigner/Services/LogicExporter.swift — the exporter's fully static
// Swift sources, extracted verbatim so generated apps are byte-identical to
// the macOS app's output. Do not edit by hand; re-run the script.
"""]
for name, doc in FUNCS:
    body = '\n'.join(literal_after(name))
    text = unescape_swift(body)
    parts.append('/** `LogicExporter.%s()` — %s */\nexport function %s(): string {\n  return `%s`;\n}\n' % (name, doc, name, ts_literal(text)))

open(os.path.abspath(OUT), 'w', encoding='utf-8').write('\n'.join(parts))
print('wrote', os.path.abspath(OUT))
