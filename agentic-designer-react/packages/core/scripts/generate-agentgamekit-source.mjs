// Regenerates src/resources/agentGameKitSource.ts from resources/AgentGameKit.swifttext.
// Usage: node scripts/generate-agentgamekit-source.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(here, '..', 'resources', 'AgentGameKit.swifttext'), 'utf8');
const escaped = source.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const out = `// GENERATED by scripts/generate-agentgamekit-source.mjs from resources/AgentGameKit.swifttext
// (a verbatim copy of AgenticDesigner/Resources/AgentGameKit.swifttext). Do not edit by hand.
//
// The SpriteKit runtime the exporter embeds into every 2D-game export as
// Shared/AgentGameKit.swift (Swift: LogicExporter.gameRuntimeSource()).

export const agentGameKitSource: string = \`${escaped}\`;
`;
writeFileSync(join(here, '..', 'src', 'resources', 'agentGameKitSource.ts'), out);
console.log('wrote src/resources/agentGameKitSource.ts', out.length, 'bytes');
