// Layer five of the product-truth check: the flows exist as DATA, so the
// navigation they promise is turned into an XCUITest that actually taps
// through it. Lives beside the exporter because exportSwiftUISource writes it.

import type { DesignNode } from '../../models/DesignNode';
import type { LogicFlow } from '../../models/LogicModels';
import { accessibilityIdentifier } from './helpers';

export interface NavigationCase {
  buttonIdentifier: string;
  buttonName: string;
  destinationIdentifier: string;
  destinationScreen: string;
}

/// Builds the XCUITest source for a project's screens and flows.
export function source(appName: string, screens: DesignNode[], flows: LogicFlow[]): string {
  const firstScreen = screens[0];
  const launchAssertions = (firstScreen?.children ?? [])
    .filter(isAssertable)
    .slice(0, 4)
    .map(
      (node) => `        XCTAssertTrue(
            app.descendants(matching: .any)["${accessibilityIdentifier(node)}"].waitForExistence(timeout: 5),
            "${node.name} should be visible on ${firstScreen?.name ?? 'the first screen'}"
        )`,
    )
    .join('\n');

  const cases = navigationCases(screens, flows);
  const navigationTests = cases
    .map(
      (testCase, index) => `    /// ${testCase.buttonName} promises navigation to ${testCase.destinationScreen} — this proves it.
    func testNavigation${index + 1}_${sanitize(testCase.buttonName)}To${sanitize(testCase.destinationScreen)}() throws {
        let app = XCUIApplication()
        app.launch()

        let control = app.descendants(matching: .any)["${testCase.buttonIdentifier}"]
        XCTAssertTrue(control.waitForExistence(timeout: 5), "${testCase.buttonName} should exist")
        control.tap()

        XCTAssertTrue(
            app.descendants(matching: .any)["${testCase.destinationIdentifier}"].waitForExistence(timeout: 5),
            "Tapping ${testCase.buttonName} should show ${testCase.destinationScreen}"
        )
    }`,
    )
    .join('\n\n');

  const noNavigationNote =
    cases.length === 0
      ? `
    // No navigation test was generated: no control on these screens has a
    // navigate flow bound to it yet. Wire one with apply_logic_actions and
    // re-export to get a real end-to-end assertion here.`
      : '';

  return `//
//  ${appName}UITests.swift
//  Generated by AgenticDesigner — do not hand-edit; regenerate instead.
//
//  These tests address elements by the accessibility identifiers the
//  exporter derives from your layer names, so renaming a layer renames
//  its test hook too.
//

import XCTest

final class ${appName}UITests: XCTestCase {

    override func setUpWithError() throws {
        continueAfterFailure = false
    }

    /// The app launches and the first screen renders its content.
    func testLaunchesAndShowsFirstScreen() throws {
        let app = XCUIApplication()
        app.launch()
        XCTAssertTrue(app.wait(for: .runningForeground, timeout: 10), "App should reach the foreground")
${launchAssertions.length === 0 ? '        // The first screen has no named elements to assert.' : launchAssertions}
    }
${noNavigationNote}
${navigationTests}
}
`;
}

/// A control is testable when a tap on it runs a flow containing a navigate
/// block, and the destination screen has something to assert.
export function navigationCases(screens: DesignNode[], flows: LogicFlow[]): NavigationCase[] {
  const cases: NavigationCase[] = [];
  const allNodes = screens.flatMap(flatten);

  for (const flow of flows) {
    const event = flow.blocks.find((b) => b.type === 'onTap');
    if (event === undefined) continue;
    const boundId =
      event.connectedDesignNodeId ??
      event.parameters.map((p) => p.nodeReference).find((r): r is string => r !== undefined);
    if (boundId === undefined) continue;
    const control = allNodes.find((n) => n.id === boundId);
    if (control === undefined) continue;

    const navigate = flow.blocks.find((b) => b.type === 'navigate');
    if (navigate === undefined) continue;
    const destinationId = navigate.parameters.find((p) => p.key === 'screen')?.nodeReference;
    if (destinationId === undefined) continue;
    const destination = screens.find((s) => s.id === destinationId);
    if (destination === undefined) continue;
    const anchor = destination.children.find(isAssertable);
    if (anchor === undefined) continue;

    cases.push({
      buttonIdentifier: accessibilityIdentifier(control),
      buttonName: control.name,
      destinationIdentifier: accessibilityIdentifier(anchor),
      destinationScreen: destination.name,
    });
  }
  return cases;
}

/// Text and controls make stable anchors; decorative art does not.
function isAssertable(node: DesignNode): boolean {
  switch (node.type) {
    case 'Text':
    case 'Button':
    case 'Input':
      return node.name.length > 0;
    default:
      return false;
  }
}

function flatten(node: DesignNode): DesignNode[] {
  return [node, ...node.children.flatMap(flatten)];
}

function sanitize(raw: string): string {
  const cleaned = raw.replace(/[^A-Za-z0-9]+/g, '');
  return cleaned.length === 0 ? 'Element' : cleaned;
}

export const UITestGenerator = { source, navigationCases };
